// Bakes the walking routes residents take to their timetabled activities into src/npc-routes.js.
// The room Worker cannot build the island scene, so routes are found here once on the full obstacle grid.
// Run `node scripts/bake-npc-routes.mjs` after moving furniture, a home, or a venue.
import {writeFileSync} from 'node:fs';
import * as T from 'three';

// The warung sign paints a canvas. Node has none, and the routes only need the obstacles.
const pen=new Proxy({},{get:(store,key)=>key==='measureText'?()=>({width:10}):key in store?store[key]:()=>{},set:(store,key,value)=>{store[key]=value;return true;}});
globalThis.document??={createElement:()=>({width:0,height:0,style:{},getContext:()=>pen})};

const {buildEnvironment,WARUNG_FOOTPRINT}=await import('../src/environment.js');
const {sportObstacles}=await import('../src/island-sports.js');
const {createNavigation}=await import('../src/navigation.js');
const {groundHeight,SWIM_LEVEL}=await import('../shared/mobility.js');
const {outings}=await import('../src/island-life.js');

export function residentRoads(){
  const environment=buildEnvironment(T,new T.Scene(),{shadowSize:16});
  // Residents keep to sand they can stand on and give furniture the same berth as the auto-walk.
  return createNavigation(environment.obstacles.concat(sportObstacles,WARUNG_FOOTPRINT),[],
    {clearance:.33,passable:(x,z)=>groundHeight(x,z)>SWIM_LEVEL+.1});
}

if(import.meta.url===`file://${process.argv[1]}`){
  const roads=residentRoads(),routes={};
  for(const {key,from,to} of outings.requests){
    const steps=roads.path(from,to);
    if(!steps)throw new Error('No walkable route for '+key);
    // A dock just inside furniture clearance, like a palm's approach, ends one short step past the grid.
    if(Math.hypot(steps.at(-1).x-to.x,steps.at(-1).z-to.z)>.01)steps.push(to);
    routes[key]=[from,...steps].map(p=>[Math.round(p.x*100)/100,Math.round(p.z*100)/100]);
  }
  const lines=Object.entries(routes).sort(([a],[b])=>a.localeCompare(b,'en',{numeric:true}))
    .map(([key,points])=>`  '${key}':${JSON.stringify(points)},`);
  writeFileSync(new URL('../src/npc-routes.js',import.meta.url),
    '// Generated by scripts/bake-npc-routes.mjs. Run it again after moving furniture or a resident\'s home.\n'+
    'export const NPC_ROUTES={\n'+lines.join('\n')+'\n};\n');
  console.log('Baked',lines.length,'resident routes.');
}
